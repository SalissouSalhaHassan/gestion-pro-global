-- 1. Create the avances_history table to track deposit movements
CREATE TABLE IF NOT EXISTS public.avances_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    advance_id BIGINT REFERENCES public.avances_clients(id) ON DELETE CASCADE,
    action TEXT NOT NULL,
    amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    utilisateur TEXT,
    notes TEXT,
    date_action TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Add an index to speed up history retrieval for a specific advance
CREATE INDEX IF NOT EXISTS idx_avances_history_advance_id ON public.avances_history(advance_id);

-- 3. Set up Row Level Security (RLS) to allow authenticated access
ALTER TABLE public.avances_history ENABLE ROW LEVEL SECURITY;

-- Allow read access for authenticated users
CREATE POLICY "Allow read access for authenticated users on avances_history"
ON public.avances_history
FOR SELECT
TO authenticated
USING (true);

-- Allow insert access for authenticated users
CREATE POLICY "Allow insert access for authenticated users on avances_history"
ON public.avances_history
FOR INSERT
TO authenticated
WITH CHECK (true);
